const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const Module = require('node:module');
const root = path.resolve(__dirname, '../../..');
const { ObsidianVault } = require('../../../CanvasRelay/relay/obsidian-vault');
const tags = require('../../../CanvasRelay/relay/canvas-card-tags');
const { canvasDiagramMarkdown } = require('../../../CanvasRelay/relay/canvas-diagram');
const output = path.resolve(process.argv[2]);
const cases = JSON.parse(fs.readFileSync(path.join(__dirname, 'tag-cases.json')));
let checks = 0;
const check = (value, name) => { assert.ok(value, name); checks++; console.log('PASS', name); };
for (const example of cases) check(tags.markdown(example.input) === example.markdown, 'shared tag syntax ' + checks);
const oldSource = execFileSync('git', ['show', '624597f62326df776099e90a626630e52e751803:CanvasRelay/relay/obsidian-vault.js'], { cwd: root, encoding: 'utf8' });
const previous = new Module(path.join(root, 'CanvasRelay/relay/obsidian-vault.baseline.cjs'), module);
previous.filename = previous.id; previous.paths = module.paths;
previous._compile(oldSource, previous.filename);
const BaselineVault = previous.exports.ObsidianVault;
const source = fs.readFileSync(path.join(output, 'tagged-scene.json'));
const untagged = fs.readFileSync(path.join(output, 'untagged-scene.json'));
const scene = JSON.parse(source);
const image = fs.readFileSync(path.join(output, 'preview.png'));
const memoBoundary = '\n<!-- ccr:markdown-memo:v1 -->\n';
const memo = '\ufeff## 메모\r\n\r\n유일 e\u0301 🖊️\r\n[[사용자 원문]]  \r\n';
const directory = name => { const d = path.join(output, name); fs.mkdirSync(d); return d; };
const hash = data => crypto.createHash('sha256').update(data).digest('hex');
const baselineRoot = directory('baseline-vault');
const baseline = new BaselineVault(baselineRoot);
const oldSaved = baseline.saveCanvas(scene.id, scene.revision, source, image, null);
const oldManaged = baseline.note(oldSaved.path).text.split(memoBoundary)[0];
const diagram = canvasDiagramMarkdown(scene);
check(diagram.length > 0 && oldManaged.endsWith(diagram), 'actual baseline generated structured plus diagram');
const oldStructured = oldManaged.slice(0, -diagram.length);
const start = oldStructured.indexOf('\n## 그림의 글자와 관계\n');
check(start > 0, 'baseline legacy prefix acquired from actual old generator');
const legacy = oldStructured.slice(0, start);
const newRoot = directory('new-vault');
const current = new ObsidianVault(newRoot);
const created = current.saveCanvas(scene.id, scene.revision, source, image, null);
const newManaged = current.note(created.path).text.split(memoBoundary)[0];
check(newManaged.includes('\n### 카드 태그\n') && newManaged.includes(': #REA_TAG_20261021_A\n'), 'real Markdown tag emitted outside preformatted content');
check(newManaged.indexOf('### 카드 태그') > newManaged.lastIndexOf('</pre>'), 'tag section follows original node text');
const newStructured = newManaged.slice(0, -diagram.length);
let index = 0;
for (const representation of [legacy, oldStructured, oldManaged, newStructured, newManaged]) {
  const target = directory('representation-' + index++);
  const vault = new ObsidianVault(target);
  const saved = vault.saveCanvas(scene.id, scene.revision, source, image, null);
  const document = representation + memoBoundary + memo;
  fs.writeFileSync(path.join(target, saved.path), document);
  const before = fs.readFileSync(path.join(target, saved.path));
  const read = new ObsidianVault(target).canvas(scene.id);
  check(Buffer.from(read.sceneJSONBase64, 'base64').equals(source), 'five-format fresh read preserves exact scene ' + index);
  check(read.noteSha256 === hash(before) && fs.readFileSync(path.join(target, saved.path)).equals(before), 'read does not rewrite old Markdown or suffix ' + index);
  const updated = structuredClone(scene); updated.revision++;
  const raw = Buffer.from(JSON.stringify(updated));
  const result = vault.saveCanvas(scene.id, updated.revision, raw, image, read.noteSha256);
  const reopened = new ObsidianVault(target).canvas(scene.id);
  check(Buffer.from(reopened.sceneJSONBase64, 'base64').equals(raw), 'explicit CAS save reopens source ' + index);
  check(vault.note(result.path).text.endsWith(memoBoundary + memo), 'BOM NFD CRLF memo suffix preserved ' + index);
}
const noScene = JSON.parse(untagged);
const noOld = new BaselineVault(directory('untagged-old')), noNew = new ObsidianVault(directory('untagged-new'));
const noA = noOld.saveCanvas(noScene.id, noScene.revision, untagged, image, null);
const noB = noNew.saveCanvas(noScene.id, noScene.revision, untagged, image, null);
check(noOld.note(noA.path).text === noNew.note(noB.path).text, 'untagged managed Markdown is byte-identical to old generator');

const originalNote = fs.readFileSync(path.join(newRoot, created.path));
const tampered = originalNote.toString().replace(': #REA_TAG_20261021_A\n', ': #REA_BAD_20261021_A\n');
fs.writeFileSync(path.join(newRoot, created.path), tampered);
assert.throws(() => current.canvas(scene.id), { status: 409 });
assert.throws(() => current.saveCanvas(scene.id, scene.revision, source, image, created.noteSha256), { status: 409 });
check(fs.readFileSync(path.join(newRoot, created.path)).equals(Buffer.from(tampered)), 'manual tag-line edit is preserved and refused, not normalized away');
const assets = fs.readdirSync(path.join(newRoot, 'CCR Canvas/Assets'));
check(assets.some(name => name.endsWith('-' + hash(source) + '.json')) && assets.some(name => name.endsWith('-' + hash(image) + '.png')), 'original scene and preview assets retained after conflict');

const staleRoot = directory('stale-vault'), stale = new ObsidianVault(staleRoot);
const first = stale.saveCanvas(scene.id, scene.revision, source, image, null);
const editedMemo = stale.note(first.path).text + memoBoundary + memo;
fs.writeFileSync(path.join(staleRoot, first.path), editedMemo);
assert.throws(() => stale.saveCanvas(scene.id, scene.revision, source, image, first.noteSha256), { status: 409 });
check(stale.note(first.path).text === editedMemo, 'stale CAS preserves external Markdown bytes');

const a = scene.annotations.find(x => x.author === '카드 태그');
const mixedUUID = structuredClone(scene);
mixedUUID.annotations.find(x => x.id === a.id).nodeId = a.nodeId.toLowerCase();
check(tags.rows(mixedUUID)[0].tags[0] === a.text, 'UUID identity matches Swift without rewriting raw IDs');
const nfdAuthor = structuredClone(scene);
nfdAuthor.annotations.find(x => x.id === a.id).author = '카드 태그'.normalize('NFD');
check(tags.rows(nfdAuthor).length === 0, 'author marker requires exact bytes');
for (const change of ['orphan', 'duplicate-id', 'duplicate-name', 'html', 'newline', 'null']) {
  const value = structuredClone(scene);
  const record = value.annotations.find(x => x.id === a.id);
  if (change === 'orphan') record.nodeId = crypto.randomUUID();
  if (change === 'duplicate-id') value.annotations.push(structuredClone(record));
  if (change === 'duplicate-name') value.annotations.push({ ...record, id: crypto.randomUUID(), text: record.text.toLowerCase() });
  if (change === 'html') record.text = '#tag<script>';
  if (change === 'newline') record.text = '#tag\n#injected';
  if (change === 'null') record.text = null;
  const before = JSON.stringify(value);
  check(tags.rows(value).length === 0 && JSON.stringify(value) === before, 'malformed records not guessed or modified ' + change);
}
const nfd = structuredClone(scene);
nfd.annotations.find(x => x.id === a.id).text = '#검토';
check(tags.rows(nfd)[0].tags[0] === '#검토' && tags.key('#검토') === tags.key('#검토'), 'NFD tag identity compares without rewriting raw text');
const huge = structuredClone(scene);
for (const node of huge.nodes) node.text = 'x'.repeat(35000);
const hugeBytes = Buffer.from(JSON.stringify(huge));
const oldBudget = new BaselineVault(directory('budget-old')), newBudget = new ObsidianVault(directory('budget-new'));
const oldB = oldBudget.saveCanvas(huge.id, huge.revision, hugeBytes, image, null);
const newB = newBudget.saveCanvas(huge.id, huge.revision, hugeBytes, image, null);
check(oldBudget.note(oldB.path).text === newBudget.note(newB.path).text, 'tags never steal old node-link projection budget');
check(Buffer.from(newBudget.canvas(huge.id).sceneJSONBase64, 'base64').equals(hugeBytes), 'omitted preview leaves full canonical tag JSON intact');
fs.writeFileSync(path.join(output, 'relay-result.json'), JSON.stringify({ passed: true, checks,
  baselineCommit: '624597f62326df776099e90a626630e52e751803', baselineSourceSHA256: hash(oldSource),
  sourceSHA256: hash(source), realOfflineVaultModule: true, HTTP: false, liveVault: false,
  actualObsidianIndexAccepted: false }, null, 2) + '\n');
console.log('CARD_TAG_OFFLINE_RELAY_OK', checks);
